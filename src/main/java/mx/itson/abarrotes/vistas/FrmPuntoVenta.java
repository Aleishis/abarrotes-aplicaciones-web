    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        Producto p = (Producto) cmbProductos.getSelectedItem();
        if (p == null) return;
        int cantidad = (int) spnCantidad.getValue();

        // Si el producto ya esta en el carrito, solo se suma la cantidad
        for (DetalleVenta d : carrito) {
            if (d.getProductoId() == p.getId()) {
                d.setCantidad(d.getCantidad() + cantidad);
                actualizarTabla();
                return;
            }
        }

        carrito.add(new DetalleVenta(p.getId(), p.getNombre(), cantidad, p.getPrecio()));
        actualizarTabla();
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnQuitarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitarActionPerformed
        int fila = tblCarrito.getSelectedRow();
        if (fila == -1) return;
        carrito.remove(fila);
        actualizarTabla();
    }//GEN-LAST:event_btnQuitarActionPerformed

    private void btnCobrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCobrarActionPerformed
        if (carrito.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El carrito esta vacio");
            return;
        }
        try {
            Venta venta = ApiCliente.registrarVenta(carrito);
            JOptionPane.showMessageDialog(this,
                    "Venta #" + venta.getId() + " registrada.\nTotal: $" + venta.getTotal());
            carrito.clear();
            actualizarTabla();
            cargarProductos(); // el stock cambio, se recarga el combo
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }
    }//GEN-LAST:event_btnCobrarActionPerformed

