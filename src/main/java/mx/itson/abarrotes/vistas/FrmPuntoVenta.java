    /** Llena el combo con los productos de la API. */
    private void cargarProductos() {
        try {
            cmbProductos.removeAllItems();
            for (Producto p : ApiCliente.listarProductos()) {
                cmbProductos.addItem(p);
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }
    }

    /** Vuelve a llenar la tabla con lo que hay en el carrito y calcula el total. */
    private void actualizarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblCarrito.getModel();
        modelo.setRowCount(0); // borra todas las filas
        double total = 0;
        for (DetalleVenta d : carrito) {
            modelo.addRow(new Object[]{d.getNombre(), d.getCantidad(), d.getPrecioUnitario(), d.getSubtotal()});
            total += d.getSubtotal();
        }
        lblTotal.setText(String.format("Total: $%.2f", total));
    }

